#!/usr/bin/env python3
"""Generate android NativeStrings.java from tools/native_strings.json (native-layer i18n, item: 50 literals + TR/DE/FA/UR)."""
import json,os
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d=json.load(open(os.path.join(R,'tools','native_strings.json'),encoding='utf-8'))
order=d['order']
def esc(s):return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
out=[]
out.append('package com.ahmedalajmi.alsaer;\n')
out.append('import android.content.Context;')
out.append('import org.json.JSONObject;')
out.append('import java.util.HashMap;')
out.append('import java.util.Map;\n')
out.append('/**')
out.append(' * كل نصوص الطبقة الأصلية تتبع لغة التطبيق المختارة (تُقرأ من مرآة حالة الويب alsaer_webstore_mirror).')
out.append(' * GENERATED by tools/native_strings_gen.py from tools/native_strings.json — do not edit by hand.')
out.append(' */')
out.append('public class NativeStrings {')
out.append('    private static final String[] LANGS = {'+', '.join(esc(x) for x in order)+'};')
out.append('    private static final Map<String, String[]> T = new HashMap<>();')
out.append('    static {')
for k in sorted(d['strings']):
    v=d['strings'][k]
    assert len(v)==len(order),k
    out.append('        T.put(%s, new String[]{%s});'%(esc(k),', '.join(esc(x) for x in v)))
out.append('    }\n')
out.append('    /** اللغة المختارة في التطبيق (ui.lang في المرآة)، مع الرجوع للعربية عند أي غموض — كما في langResolve(). */')
out.append('    public static String lang(Context c) {')
out.append('        try {')
out.append('            String raw = c.getSharedPreferences("alsaer_webstore_mirror", 0).getString("tawba_v1", null);')
out.append('            if (raw != null) {')
out.append('                JSONObject ui = new JSONObject(raw).optJSONObject("ui");')
out.append('                String l = ui != null ? ui.optString("lang", "") : "";')
out.append('                for (String x : LANGS) if (x.equals(l)) return l;')
out.append('            }')
out.append('        } catch (Exception ignored) { }')
out.append('        return "ar";')
out.append('    }\n')
out.append('    public static String get(Context c, String key) { return get(c, key, lang(c)); }')
out.append('    public static String get(Context c, String key, String lang) {')
out.append('        String[] v = T.get(key);')
out.append('        if (v == null) return key;')
out.append('        for (int i = 0; i < LANGS.length; i++)')
out.append('            if (LANGS[i].equals(lang) && v[i] != null && !v[i].isEmpty()) return v[i];')
out.append('        return v[0];')
out.append('    }')
out.append('}')
p=os.path.join(R,'android/app/src/main/java/com/ahmedalajmi/alsaer/NativeStrings.java')
open(p,'w',encoding='utf-8',newline='\n').write('\n'.join(out)+'\n')
print('wrote',p,len(d['strings']),'strings')
